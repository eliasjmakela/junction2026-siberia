import { useMemo, useRef, useState } from 'react'
import { Arrow } from '../components/Arrow'
import type { Values } from '../form/schema'
import { generateScreening } from './api'
import { BUDGET_SECONDS, targetText, totalSeconds, type Question, type Screening } from './core'
import { profileFrom } from './profile'
import { loadPublished, removePublished, savePublished, type Published } from './storage'
import '../form/fields.css'
import './screening.css'

type Draft = Screening & { generatedAt: string }

function formatTime(iso: string) {
  return new Date(iso).toLocaleString('en-GB', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' })
}

function matchText(q: Question) {
  return q.kind === 'yesno' ? (q.expect === 'yes' ? 'Yes' : 'No') : targetText(q)
}

function SourceLine({ s }: { s: Pick<Screening, 'source' | 'model'> }) {
  return s.source === 'ai' ? (
    <span className="qc-source qc-source--ai">
      <b>Generated by AI</b>
      {s.model && <span> · {s.model}</span>}
    </span>
  ) : (
    <span className="qc-source">
      <b>Generated from your answers</b>
    </span>
  )
}

function QuestionList({ questions, onRemove }: { questions: Question[]; onRemove?: (id: string) => void }) {
  return (
    <ol className="qc-list">
      {questions.map((q, i) => (
        <li key={q.id} className="qc-item">
          <span className="qc-item__n">{i + 1}</span>
          <div className="qc-item__body">
            <p className="qc-item__q">{q.text}</p>
            <p className="qc-item__meta">
              <span>{q.kind === 'yesno' ? 'Yes / No' : `Number, ${q.unit}`}</span>
              <span>Checks: {q.requirement}</span>
              <span>Matches: {matchText(q)}</span>
            </p>
          </div>
          {onRemove && (
            <button type="button" className="qc-item__remove" onClick={() => onRemove(q.id)} aria-label={`Remove question ${i + 1}`}>
              Remove
            </button>
          )}
        </li>
      ))}
    </ol>
  )
}

/**
 * The company reviews the quick check for one role: generate it, see which
 * requirement each question checks, remove questions, and publish. Only the
 * questions themselves are AI-generated; everything around them is fixed copy.
 */
export function ScreeningReview({ values }: { values: Values }) {
  const profile = useMemo(() => profileFrom(values), [values])
  const fingerprint = useMemo(() => JSON.stringify(profile), [profile])
  const [published, setPublished] = useState<Published | null>(loadPublished)
  const [draft, setDraft] = useState<Draft | null>(null)
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState('')
  const listRef = useRef<HTMLDivElement>(null)

  async function generate() {
    setBusy(true)
    setStatus('Generating questions…')
    const s = await generateScreening(profile)
    setBusy(false)
    if (!s.questions.length) {
      setDraft(null)
      setStatus('Not enough requirements to build a quick check. Answer more of the role questions and try again.')
      return
    }
    setDraft({ ...s, generatedAt: new Date().toISOString() })
    setStatus(`${s.questions.length} questions ready for review.`)
    requestAnimationFrame(() => listRef.current?.focus())
  }

  function remove(id: string) {
    setDraft((d) => (d ? { ...d, questions: d.questions.filter((q) => q.id !== id) } : d))
    setStatus('Question removed.')
  }

  function publish() {
    if (!draft?.questions.length) return
    const record: Published = {
      questions: draft.questions,
      source: draft.source,
      model: draft.model,
      role: { title: profile.title, company: profile.company },
      fingerprint,
      generatedAt: draft.generatedAt,
      approvedAt: new Date().toISOString(),
    }
    if (!savePublished(record)) {
      setStatus('Could not publish the quick check. Try again.')
      return
    }
    setPublished(record)
    setDraft(null)
    setStatus('Quick check published.')
  }

  function edit() {
    if (!published) return
    setDraft({ questions: published.questions, source: published.source, model: published.model, generatedAt: published.generatedAt })
    setStatus('')
  }

  function unpublish() {
    removePublished()
    setPublished(null)
    setStatus('Quick check unpublished.')
  }

  const seconds = draft ? totalSeconds(draft.questions) : 0

  return (
    <section className="qc" aria-labelledby="qc-title">
      <h2 id="qc-title" className="qc__title">Quick check for attendees</h2>
      <p className="qc__lede">
        Up to 8 yes/no and number questions that attendees answer in about {BUDGET_SECONDS} seconds to see how well this role matches them.
        You review every question before it is published.
      </p>

      {draft ? (
        <div className="qc__panel" ref={listRef} tabIndex={-1} aria-label="Quick check draft">
          <p className="qc__meta">
            <SourceLine s={draft} />
            <span>
              {draft.questions.length} {draft.questions.length === 1 ? 'question' : 'questions'} · about {seconds} seconds
            </span>
          </p>
          {draft.questions.length ? (
            <QuestionList questions={draft.questions} onRemove={remove} />
          ) : (
            <p className="qc__empty">No questions left. Generate the quick check again to start over.</p>
          )}
          <div className="qc__actions">
            <button type="button" className="btn" onClick={publish} disabled={!draft.questions.length}>
              Publish quick check <Arrow />
            </button>
            <button type="button" className="btn-quiet" onClick={generate} disabled={busy}>
              {busy ? 'Generating…' : 'Generate again'}
            </button>
          </div>
        </div>
      ) : published ? (
        <div className="qc__panel">
          <p className="qc__meta">
            <span className="qc-source qc-source--live">
              <b>Published</b> · {formatTime(published.approvedAt)}
            </span>
            <SourceLine s={published} />
            <span>
              {published.questions.length} questions · about {totalSeconds(published.questions)} seconds
            </span>
          </p>
          {published.fingerprint !== fingerprint && (
            <p className="qc__notice">The role has changed since this quick check was published. Generate it again to match the role.</p>
          )}
          <QuestionList questions={published.questions} />
          <div className="qc__actions">
            <a className="btn" href="#/check">
              Open attendee view <Arrow />
            </a>
            <button type="button" className="btn-quiet" onClick={edit}>
              Edit questions
            </button>
            <button type="button" className="btn-quiet" onClick={generate} disabled={busy}>
              {busy ? 'Generating…' : 'Generate again'}
            </button>
            <button type="button" className="btn-quiet" onClick={unpublish}>
              Unpublish
            </button>
          </div>
        </div>
      ) : (
        <div className="qc__actions">
          <button type="button" className="btn" onClick={generate} disabled={busy}>
            {busy ? 'Generating…' : 'Generate quick check'} <Arrow />
          </button>
        </div>
      )}

      <p className="status" role="status">
        {status}
      </p>

      <p className="qc__privacy">
        Questions cover job requirements only. Questions about age, gender, family, health, origin, nationality, beliefs or other protected
        grounds are removed automatically, and no question asks for a name or contact details. Attendee answers stay on their own device and
        are never sent to you.
      </p>
    </section>
  )
}
