const MINE_KEY = 'plainly:apply:mine'
const MIN_ANSWER = 20
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/

type Step = { kind: 'intro' } | { kind: 'pick' } | { kind: 'answer'; index: number } | { kind: 'contact' } | { kind: 'review' }

function readMine(): string | null {
  try {
    return localStorage.getItem(MINE_KEY)
  } catch {
    return null
  }
}

function writeMine(id: string | null) {
  try {
    if (id) localStorage.setItem(MINE_KEY, id)
    else localStorage.removeItem(MINE_KEY)
  } catch {
    /* storage unavailable: the submitted view lasts for this visit only */
  }
}

const purposeOf = (l: Listing) => l.brief.sources.find((s) => s.field === 'purpose')?.text
const statusOf = (l: Listing) => (l.status ? GOALS[l.status].name : null)
const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`

function SourceNote({ listing }: { listing: Listing }) {
  if (listing.set.source === 'sample') return null
  if (listing.set.source === 'ai')
    return (
      <p className="apply-source">
        <span className="apply-source__ai">Generated by AI</span> from the company's role description and reviewed by the company
      </p>
    )
  return <p className="apply-source">Built from the company's role description and reviewed by the company</p>
}

function ListingCard({ listing, checked, disabled, onToggle }: { listing: Listing; checked: boolean; disabled: boolean; onToggle: () => void }) {
  const purpose = purposeOf(listing)
  const status = statusOf(listing)
  const goal = goalOf(listing.values)
  return (
    <label className={`apply-card${checked ? ' is-checked' : ''}${disabled ? ' is-disabled' : ''}`} data-listing={listing.id}>
      <input type="checkbox" checked={checked} disabled={disabled} onChange={onToggle} />
      <span className="apply-card__top">
        <span className="apply-card__status">{status ?? ''}</span>
        <span className="apply-card__mark" aria-hidden="true" />
      </span>
      <span className="apply-card__title">{listing.title}</span>
      <span className="apply-card__company">{listing.company}</span>
      {purpose && (
        <span className="apply-card__purpose">
          <span className="apply-card__lead">This role exists so that </span>
          {purpose}
        </span>
      )}
      <span className="apply-card__meta">
        <span>{plural(listing.set.questions.length, 'question', 'questions')}</span>
        <span className="apply-card__sky" aria-hidden="true">
          <Sky thumb seed={listing.seed} goal={goal} fingerprint={roleFingerprint(listing.values)} step={8} {...skyStars(listing.values, () => true)} complete />
        </span>
              </span>
    </label>
  )
}

function Progress({ current, total, detail, action }: { current: number; total: number; detail?: string; action?: ReactNode }) {
  return (
    <div className="progress apply-progress" aria-label={`Step ${current} of ${total}`}>
      <ol className="progress__bars" aria-hidden="true">
        {Array.from({ length: total }, (_, i) => (
          <li key={i} className={i + 1 === current ? 'is-current' : i + 1 < current ? 'is-done' : undefined} />
        ))}
      </ol>
      <span>
        Step {current} of {total}
        {detail && <> · {detail}</>}
      </span>
      {action}
    </div>
  )
}

function Submitted({ app, listings, onDeleted, action }: { app: Application; listings: Listing[]; onDeleted: () => void; action?: ReactNode }) {
  const [confirming, setConfirming] = useState(false)
  const [status, setStatus] = useState('')
  const headingRef = useRef<HTMLHeadingElement>(null)
  const confirmRef = useRef<HTMLButtonElement>(null)
  const picked = app.picks.map((id) => listings.find((l) => l.id === id)).filter((l): l is Listing => Boolean(l))

  useEffect(() => {
    headingRef.current?.focus()
  }, [])

  function remove() {
    if (!deleteApplication(app.id)) {
      setStatus('Could not delete the application. Try again.')
      return
    }
    onDeleted()
  }

  return (
    <section className="apply-step apply-intro" aria-labelledby="apply-done-title">
      <h1 id="apply-done-title" ref={headingRef} tabIndex={-1}>
        Application submitted
      </h1>
      <p className="hint">Keep your application code. It identifies your application if you contact City of Espoo staff.</p>

      <div className="apply-code">
        <p className="apply-label">Application code</p>
        <p className="apply-code__value">{app.code}</p>
      </div>

      <div className="apply-section">
        <h2 className="apply-label">Companies</h2>
        <ul className="apply-picked">
          {picked.map((l) => (
            <li key={l.id}>
              <b>{l.company}</b> · {l.title}
                          </li>
          ))}
        </ul>
      </div>

      <div className="apply-privacy apply-next">
        <h2>What happens next</h2>
        <ul>
          <li>City of Espoo staff review applications after {EVENT.applyBy}.</li>
          <li>Invitations to {EVENT.name} are sent by e-mail to the address you gave.</li>
          <li>A person decides every invitation. AI-drafted scores support that decision.</li>
          <li>You can delete your application and its answers at any time.</li>
        </ul>
      </div>

      <div className="apply-delete">
        {confirming ? (
          <>
            <p className="apply-delete__q" id="apply-delete-q">
              Delete this application and all its answers? This cannot be undone.
            </p>
            <div className="actions">
              <button type="button" className="btn" ref={confirmRef} onClick={remove} aria-describedby="apply-delete-q">
                Delete application
              </button>
              <button type="button" className="btn-quiet" onClick={() => setConfirming(false)}>
                Keep application
              </button>
            </div>
          </>
        ) : (
          <button
            type="button"
            className="btn-quiet"
            onClick={() => {
              setConfirming(true)
              requestAnimationFrame(() => confirmRef.current?.focus())
            }}
          >
            Delete my application
          </button>
        )}
      </div>
      <p className="status" role="status">
        {status}
      </p>
      {action && <div className="actions apply-actions">{action}</div>}
    </section>
  )
}

/**
 * The applicant's flow at #/apply: choose up to MAX_PICKS companies, answer
 * their questions, give an e-mail for the invitation and consent, review and
 * submit. Answers are stored for City of Espoo staff review; this view never
 * calls an AI endpoint.
 */
export function Apply() {
  const state = useEvent()
  const listings = state.allListings
  const [mineId, setMineId] = useState<string | null>(readMine)
  const mine = mineId ? state.applications.find((a) => a.id === mineId) ?? null : null

  const [step, setStep] = useState<Step>({ kind: 'intro' })
  const [picks, setPicks] = useState<string[]>([])
  const [answers, setAnswers] = useState<Record<string, Record<string, string>>>({})
  const [email, setEmail] = useState('')
  const [consent, setConsent] = useState(false)
  const [invalid, setInvalid] = useState<Set<string>>(new Set())
  const [error, setError] = useState('')
  const [status, setStatus] = useState('')
  const [backToReview, setBackToReview] = useState(false)
  const [demoRunning, setDemoRunning] = useState(false)
  const [demoMode, setDemoMode] = useState(false)
  const demoRun = useRef(0)
  const cursorRef = useRef<HTMLDivElement>(null)
  const headingRef = useRef<HTMLHeadingElement>(null)


  const picked = picks.map((id) => listings.find((l) => l.id === id)).filter((l): l is Listing => Boolean(l))
  const total = picked.length + 3 // pick, one per company, contact, review
  const current =
    step.kind === 'pick' ? 1 : step.kind === 'answer' ? 2 + step.index : step.kind === 'contact' ? picked.length + 2 : step.kind === 'review' ? total : 0

  function go(next: Step) {
    setInvalid(new Set())
    setError('')
    setStep(next)
    window.scrollTo({ top: 0 })
    requestAnimationFrame(() => headingRef.current?.focus())
  }

  function toggle(id: string) {
    setError('')
    setPicks((prev) => {
      const next = prev.includes(id) ? prev.filter((p) => p !== id) : prev.length < MAX_PICKS ? [...prev, id] : prev
      setStatus(next.length >= MAX_PICKS ? `${next.length} of ${MAX_PICKS} chosen. Remove one to choose another.` : `${next.length} of ${MAX_PICKS} chosen.`)
      return next
    })
  }

  function afterStep(fallback: Step) {
    if (backToReview) {
      setBackToReview(false)
      go({ kind: 'review' })
    } else go(fallback)
  }

  function submitPick(e: FormEvent) {
    e.preventDefault()
    if (!picked.length) {
      setError('Choose at least one company to continue.')
      return
    }
    setPicks(picked.map((l) => l.id))
    setStatus('')
    // A changed pick list may need new answers, so go through the questions again.
    setBackToReview(false)
    go({ kind: 'answer', index: 0 })
  }

  function setAnswer(listingId: string, qid: string, text: string) {
    setAnswers((prev) => ({ ...prev, [listingId]: { ...prev[listingId], [qid]: text.slice(0, ANSWER_MAX) } }))
    setInvalid((prev) => {
      const key = `${listingId}:${qid}`
      if (!prev.has(key)) return prev
      const next = new Set(prev)
      next.delete(key)
      return next
    })
  }

  function submitAnswers(e: FormEvent, index: number) {
    e.preventDefault()
    const l = picked[index]
    const missing = l.set.questions.filter((q) => (answers[l.id]?.[q.id] ?? '').trim().length < MIN_ANSWER)
    if (missing.length) {
      setInvalid(new Set(missing.map((q) => `${l.id}:${q.id}`)))
      setError('Answer every question to continue.')
      document.getElementById(`apply-${l.id}-${missing[0].id}`)?.focus()
      return
    }
    afterStep(index + 1 < picked.length ? { kind: 'answer', index: index + 1 } : { kind: 'contact' })
  }

  function submitContact(e: FormEvent) {
    e.preventDefault()
    const bad = new Set<string>()
    if (!EMAIL.test(email.trim())) bad.add('email')
    if (!consent) bad.add('consent')
    if (bad.size) {
      setInvalid(bad)
      setError(bad.has('email') ? 'Enter a valid e-mail address.' : 'Agree to the processing to continue.')
      document.getElementById(bad.has('email') ? 'apply-email' : 'apply-consent')?.focus()
      return
    }
    afterStep({ kind: 'review' })
  }

  function submitAll() {
    const now = new Date().toISOString()
    const app: Application = {
      id: newId(),
      code: newCode(new Set(state.allApplications.map((a) => a.code))),
      submittedAt: now,
      picks: picked.map((l) => l.id),
      answers: Object.fromEntries(
        picked.map((l) => [l.id, Object.fromEntries(l.set.questions.map((q) => [q.id, (answers[l.id]?.[q.id] ?? '').trim()]))]),
      ),
      email: email.trim(),
      consentAt: now,
      sample: demoMode || undefined,
      sets: Object.fromEntries(picked.map((l) => [l.id, setKeyOf(l.set)])),
    }
    if (!submitApplication(app)) {
      setError('Could not submit the application. Try again.')
      return
    }
    writeMine(app.id)
    setMineId(app.id)
    setPicks([])
    setAnswers({})
    setEmail('')
    setConsent(false)
    setDemoMode(false)
    setStatus('')
    setStep({ kind: 'intro' })
    window.scrollTo({ top: 0 })
  }

  function stopDemo() {
    demoRun.current += 1
    setDemoRunning(false)
    cursorRef.current?.classList.remove('is-visible', 'is-down')
  }

  // Any real click or key press during the walkthrough hands control back to the person.
  useEffect(() => {
    if (!demoRunning) return
    const takeOver = (e: Event) => {
      if (!e.isTrusted || (e.target instanceof Element && e.target.closest('.demo-control'))) return
      stopDemo()
    }
    window.addEventListener('pointerdown', takeOver, true)
    window.addEventListener('keydown', takeOver, true)
    return () => {
      window.removeEventListener('pointerdown', takeOver, true)
      window.removeEventListener('keydown', takeOver, true)
    }
  }, [demoRunning])

  /** Fills the application with synthetic sample answers, step by step, and stops at the review. */
  async function playSampleDemo(event: MouseEvent<HTMLButtonElement>) {
    if (demoRunning) {
      stopDemo()
      return
    }
    const run = demoRun.current + 1
    demoRun.current = run
    const d = demoCursor(cursorRef.current, () => demoRun.current === run)
    const plan = demoPicks(listings)
    d.show(event.currentTarget)
    setDemoRunning(true)
    setDemoMode(true)
    // A new sample application: the earlier one stays stored for staff review.
    writeMine(null)
    setMineId(null)
    setPicks([])
    setAnswers({})
    setEmail('')
    setConsent(false)
    setBackToReview(false)
    go({ kind: 'intro' })
    await delay(600)

    const clickOn = async (selector: string) => {
      const el = await d.find(selector)
      return el ? d.click(el) : false
    }

    if (!plan.length || !(await clickOn('.apply-intro .btn'))) return stopDemo()
    for (const l of plan) if (!(await clickOn(`label.apply-card[data-listing="${CSS.escape(l.id)}"]`))) return stopDemo()
    if (!(await clickOn('form.apply-step button[type="submit"]'))) return stopDemo()

    for (const l of plan) {
      for (const [i, q] of l.set.questions.entries()) {
        const box = await d.find<HTMLTextAreaElement>(`#${CSS.escape(`apply-${l.id}-${q.id}`)}`)
        if (!box || !(await d.type(box, demoAnswerFor(l, q, i), 'word'))) return stopDemo()
      }
      if (!(await clickOn('form.apply-step button[type="submit"]'))) return stopDemo()
      await delay(300)
    }

    const emailBox = await d.find<HTMLInputElement>('#apply-email')
    if (!emailBox || !(await d.type(emailBox, DEMO_EMAIL))) return stopDemo()
    if (!(await clickOn('label.apply-consent'))) return stopDemo()
    if (!(await clickOn('form.apply-step button[type="submit"]'))) return stopDemo()
    await d.find('#apply-review-title')
    await delay(400)
    setDemoRunning(false)
    d.hide()
  }

  function onDeleted() {
    writeMine(null)
    setMineId(null)
    setStatus('Application deleted.')
    go({ kind: 'intro' })
  }

  const demoButton = (
    <button type="button" className="btn-quiet demo-control" onClick={playSampleDemo} aria-pressed={demoRunning} title="Fills in the form with example answers, step by step. Click anywhere to take over.">
      {demoRunning ? 'Stop walkthrough' : demoMode ? 'Replay walkthrough' : 'Play walkthrough'}
    </button>
  )
  const cursor = (
    <div ref={cursorRef} className="demo-cursor" aria-hidden="true">
      <svg className="demo-cursor__shape" viewBox="0 0 24 32" focusable="false">
        <path d="M2 1v25l7-7 5 11 5-2-5-11h9L2 1Z" />
      </svg>
    </div>
  )

  if (mine) {
    return (
      <main className="page apply">
        <SiteHeader area="apply" />
        <Submitted app={mine} listings={listings} onDeleted={onDeleted} action={demoButton} />
        {cursor}
      </main>
    )
  }

  return (
    <main className="page apply">
      <SiteHeader area="apply" />
      {step.kind !== 'intro' && (
        <Progress
          current={current}
          total={total}
          detail={step.kind === 'answer' ? `Company ${step.index + 1} of ${picked.length}` : undefined}
          action={demoButton}
        />
      )}

      {step.kind === 'intro' && (
        <section className="apply-step apply-intro" aria-labelledby="apply-intro-title">
          <h1 id="apply-intro-title" ref={headingRef} tabIndex={-1}>
            Apply to meet companies at the event
          </h1>
          <p className="hint">
            Choose up to {MAX_PICKS} companies taking part in {EVENT.name} and answer a few short questions from each. City of Espoo staff review
            the answers and send invitations by e-mail. Apply by {EVENT.applyBy}.
          </p>

          <div className="apply-section">
            <h2 className="apply-label">How it works</h2>
            <ol className="apply-how">
              <li>Choose up to {MAX_PICKS} companies.</li>
              <li>Answer each company's questions with examples from your own work.</li>
              <li>AI drafts a score from 0 to 10 for each thing the company is looking for, with a quote from your answer as evidence.</li>
              <li>City of Espoo staff review the answers and scores and decide who is invited. A person makes every decision.</li>
            </ol>
          </div>

          <div className="apply-privacy">
            <h2>Before you start</h2>
            <ul>
              <li>City of Espoo staff review your answers for the companies you choose.</li>
              <li>AI reads the answers to one company's questions at a time. It never sees your e-mail address.</li>
              <li>Leave out your name, contact details, age, health, family and other personal details. Answer about your work and skills.</li>
              <li>Your e-mail address is used only to send the invitation.</li>
              <li>You can delete your application at any time.</li>
            </ul>
          </div>

          <div className="actions apply-actions">
            <button type="button" className="btn" onClick={() => go({ kind: 'pick' })}>
              Start application <Arrow />
            </button>
            {demoButton}
          </div>
          <p className="status" role="status">
            {status}
          </p>
        </section>
      )}

      {step.kind === 'pick' && (
        <form className="apply-step" onSubmit={submitPick} noValidate aria-labelledby="apply-pick-title">
          <h1 id="apply-pick-title" ref={headingRef} tabIndex={-1}>
            Choose up to {MAX_PICKS} companies
          </h1>
          <p className="hint">Each company has a few short questions. You answer them in the next steps.</p>
          <p className="error" role="alert">
            {error}
          </p>
          {listings.length ? (
            <fieldset className="apply-cards">
              <legend className="visually-hidden">Companies taking part</legend>
              {listings.map((l) => {
                const checked = picks.includes(l.id)
                return <ListingCard key={l.id} listing={l} checked={checked} disabled={!checked && picks.length >= MAX_PICKS} onToggle={() => toggle(l.id)} />
              })}
            </fieldset>
          ) : (
            <p className="apply-empty">No companies have published questions yet.</p>
          )}
          <p className="status" role="status">
            {status}
          </p>
          <div className="actions apply-actions">
            <button type="submit" className="btn">
              Next <Arrow />
            </button>
            <button type="button" className="btn-quiet" onClick={() => go({ kind: 'intro' })}>
              Back
            </button>
          </div>
        </form>
      )}

      {step.kind === 'answer' && picked[step.index] && (() => {
        const l = picked[step.index]
        const status = statusOf(l)
        const names = l.set.attributes.map((a) => a.name)
        return (
          <form className="apply-step" onSubmit={(e) => submitAnswers(e, step.index)} noValidate aria-labelledby="apply-answer-title" key={l.id}>
            <h1 id="apply-answer-title" ref={headingRef} tabIndex={-1}>
              {l.company}
            </h1>
            <p className="apply-byline">
              {l.title}
              {status && <span className="apply-byline__status"> · {status}</span>}
                          </p>
            <p className="hint">Answer with concrete examples of your own work, in a few sentences each. Say what you did and what came of it.</p>
            <div className="apply-scored">
              <p className="apply-scored__label">Answers are scored on</p>
              <ul>
                {names.map((n) => (
                  <li key={n}>{n}</li>
                ))}
              </ul>
              <SourceNote listing={l} />
            </div>
            <p className="error" role="alert">
              {error}
            </p>
            <ol className="apply-questions">
              {l.set.questions.map((q, i) => {
                const id = `apply-${l.id}-${q.id}`
                const value = answers[l.id]?.[q.id] ?? ''
                const bad = invalid.has(`${l.id}:${q.id}`)
                return (
                  <li key={q.id} className="qfield apply-q">
                    <label className="qfield__label apply-q__label" htmlFor={id}>
                      <span className="apply-q__n" aria-hidden="true">
                        {i + 1}
                      </span>
                      <span>{q.text}</span>
                    </label>
                    <textarea
                      id={id}
                      className={`input input--area apply-q__input${bad ? ' is-invalid' : ''}`}
                      rows={5}
                      maxLength={ANSWER_MAX}
                      value={value}
                      aria-invalid={bad || undefined}
                      aria-describedby={`${id}-count${bad ? ` ${id}-error` : ''}`}
                      onChange={(e) => setAnswer(l.id, q.id, e.target.value)}
                    />
                    <div className="apply-q__foot">
                      <span className="qfield__error" id={`${id}-error`}>
                        {bad ? 'Answer this question.' : ''}
                      </span>
                      <span className="apply-q__count" id={`${id}-count`}>
                        {value.length} / {ANSWER_MAX}
                      </span>
                    </div>
                  </li>
                )
              })}
            </ol>
            <div className="actions apply-actions">
              <button type="submit" className="btn">
                {backToReview ? 'Back to review' : 'Next'} <Arrow />
              </button>
              <button
                type="button"
                className="btn-quiet"
                onClick={() => go(step.index === 0 ? { kind: 'pick' } : { kind: 'answer', index: step.index - 1 })}
              >
                Back
              </button>
            </div>
          </form>
        )
      })()}

      {step.kind === 'contact' && (
        <form className="apply-step" onSubmit={submitContact} noValidate aria-labelledby="apply-contact-title">
          <h1 id="apply-contact-title" ref={headingRef} tabIndex={-1}>
            Where should we send the invitation?
          </h1>
          <p className="hint">Your e-mail address is used only to send the invitation. It is not shown with your answers and never sent to AI.</p>
          <p className="error" role="alert">
            {error}
          </p>
          <div className="qfield">
            <label className="qfield__label" htmlFor="apply-email">
              E-mail address
            </label>
            <input
              id="apply-email"
              className={`input apply-email${invalid.has('email') ? ' is-invalid' : ''}`}
              type="email"
              autoComplete="email"
              inputMode="email"
              value={email}
              aria-invalid={invalid.has('email') || undefined}
              onChange={(e) => {
                setEmail(e.target.value)
                setInvalid((p) => {
                  const n = new Set(p)
                  n.delete('email')
                  return n
                })
              }}
            />
          </div>
          <div className="qfield">
            <p className="qfield__label">Consent</p>
            <label className={`chip chip--multi apply-consent${invalid.has('consent') ? ' is-invalid' : ''}`}>
              <input
                id="apply-consent"
                type="checkbox"
                checked={consent}
                aria-invalid={invalid.has('consent') || undefined}
                onChange={(e) => {
                  setConsent(e.target.checked)
                  setInvalid((p) => {
                    const n = new Set(p)
                    n.delete('consent')
                    return n
                  })
                }}
              />
              <span className="chip__mark" aria-hidden="true" />
              <span>
                I agree that City of Espoo staff review my answers for the companies I choose, that AI drafts scores from my answers to support
                their decision, and that my application is kept until the event follow-up ends. I can delete it at any time.
              </span>
            </label>
          </div>
          <div className="actions apply-actions">
            <button type="submit" className="btn">
              {backToReview ? 'Back to review' : 'Review application'} <Arrow />
            </button>
            <button type="button" className="btn-quiet" onClick={() => go({ kind: 'answer', index: picked.length - 1 })}>
              Back
            </button>
          </div>
        </form>
      )}

      {step.kind === 'review' && (
        <section className="apply-step" aria-labelledby="apply-review-title">
          <h1 id="apply-review-title" ref={headingRef} tabIndex={-1}>
            Review your application
          </h1>
          <p className="hint">Check your answers before you submit. You can change any of them.</p>

          {picked.map((l, index) => (
            <div key={l.id} className="apply-sheet">
              <div className="apply-sheet__head">
                <h2 className="apply-sheet__title">
                  {l.company}
                  <span className="apply-sheet__role"> · {l.title}</span>
                </h2>
                <button
                  type="button"
                  className="apply-change"
                  aria-label={`Change answers for ${l.company}`}
                  onClick={() => {
                    setBackToReview(true)
                    go({ kind: 'answer', index })
                  }}
                >
                  Change
                </button>
              </div>
              <dl className="apply-answers">
                {l.set.questions.map((q) => (
                  <div key={q.id}>
                    <dt>{q.text}</dt>
                    <dd>{answers[l.id]?.[q.id]?.trim()}</dd>
                  </div>
                ))}
              </dl>
            </div>
          ))}

          <div className="apply-sheet">
            <div className="apply-sheet__head">
              <h2 className="apply-sheet__title">Invitation</h2>
              <button
                type="button"
                className="apply-change"
                aria-label="Change e-mail address"
                onClick={() => {
                  setBackToReview(true)
                  go({ kind: 'contact' })
                }}
              >
                Change
              </button>
            </div>
            <dl className="apply-answers">
              <div>
                <dt>E-mail address</dt>
                <dd>{email.trim()}</dd>
              </div>
              <div>
                <dt>Consent</dt>
                <dd>Given</dd>
              </div>
            </dl>
          </div>

          <div className="actions apply-actions">
            <button type="button" className="btn" onClick={submitAll}>
              Submit application <Arrow />
            </button>
            <button type="button" className="btn-quiet" onClick={() => go({ kind: 'contact' })}>
              Back
            </button>
          </div>
          <p className="status" role="status">
            {error}
          </p>
          <p className="apply-change-picks">
            <button
              type="button"
              className="apply-change"
              onClick={() => {
                setBackToReview(false)
                go({ kind: 'pick' })
              }}
            >
              Change companies
            </button>
          </p>
        </section>
      )}
      {cursor}
    </main>
  )
}
